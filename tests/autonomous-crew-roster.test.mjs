import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildCrewRosterForecast} from '../lib/crew-roster-forecast.mjs';

const sql=readFileSync(new URL('../supabase/migrations/20261112233000_ops5_autonomous_sim_crew_roster.sql',import.meta.url),'utf8');
const ui=readFileSync(new URL('../app/crew-mobility/page.tsx',import.meta.url),'utf8');

const base=()=>({
 startDate:'2026-11-16',weeks:2,asOf:'2026-11-12T09:00:00Z',
 people:[{id:'pilot1',name:'Captain',role:'PIC',employmentStatus:'draft'}],
 dutyBlocks:[],shadowFlights:[],shadowAssignments:[],draftSlots:[],
 autoSlots:[],dataComplete:true
});
const automated={
 id:'auto-1',employeeId:'pilot1',
 startsAt:'2026-11-16T08:00:00Z',endsAt:'2026-11-16T20:00:00Z'
};

test('autonomous fictional staffing is a distinct, not released calendar status',()=>{
 const input=base();input.autoSlots=[automated];
 const res=buildCrewRosterForecast(input);
 assert.equal(res.status,'preview');
 assert.equal(res.rows[0].days[0].kind,'auto');
 assert.equal(res.rows[0].days[0].events[0].state,'virtual_autogenerated');
 assert.equal(res.totals.flightApprovals,0);
 assert.equal(res.totals.verifiedTypeRatings,0);
});

test('autonomous standby blocks phantom separate free-day or standby suggestion',()=>{
 const input=base();input.people[0].employmentStatus='active';
 input.autoSlots=[automated];
 const res=buildCrewRosterForecast(input);
 assert.equal(res.rows[0].days[0].kind,'auto');
 assert.equal(res.rows[0].days[0].standbyCandidate,false);
 assert.equal(res.standby[0].PIC,null);
});

test('new duty overlapping automated standby becomes an explicit visible conflict',()=>{
 const input=base();input.autoSlots=[automated];
 input.dutyBlocks=[{id:'leave1',employeeId:'pilot1',
  startsAt:'2026-11-16T10:00:00Z',endsAt:'2026-11-16T16:00:00Z',
  kind:'absence',state:'confirmed'}];
 const res=buildCrewRosterForecast(input);
 assert.equal(res.rows[0].days[0].kind,'conflict');
});

test('broken automated slot provenance fails closed rather than claiming availability',()=>{
 const input=base();
 input.autoSlots=[{...automated,employeeId:'unknown'}];
 const res=buildCrewRosterForecast(input);
 assert.equal(res.status,'unavailable');
 assert.deepEqual(res.standby,[]);
});

test('SQL schedules daily autonomous roster, idempotent slots, and no public write access',()=>{
 assert.match(sql,/cron\.schedule\(/);
 assert.match(sql,/45 5 \* \* \*/);
 assert.match(sql,/generate_autonomous_crew_roster/);
 assert.match(sql,/p_day\+84/);
 assert.match(sql,/ON CONFLICT\(organization_id,duty_day,crew_role\) DO NOTHING/);
 assert.match(sql,/ENABLE ROW LEVEL SECURITY/);
 assert.match(sql,/REVOKE ALL ON public\.%I FROM PUBLIC,anon,authenticated/);
 assert.match(sql,/GRANT SELECT ON public\.%I TO authenticated/);
 assert.match(sql,/owner_user_id=\(SELECT auth\.uid\(\)\)/);
 assert.doesNotMatch(sql,/GRANT (?:INSERT|UPDATE|DELETE).*TO authenticated/);
});

test('SQL respects duties, shadow flights and pre-existing human roster drafts',()=>{
 assert.match(sql,/FROM public\.crew_duty_blocks/);
 assert.match(sql,/FROM public\.shadow_crew_assignments/);
 assert.match(sql,/FROM public\.sim_crew_roster_revisions/);
 assert.match(sql,/11 hours 30 minutes/);
 assert.match(sql,/COUNT\(\*\)|count\(\*\)/);
});

test('fictional NPC messages are internal only, and unverified credentials remain visible',()=>{
 assert.match(sql,/CREATE TABLE public\.sim_crew_auto_messages/);
 assert.match(sql,/delivered_in_simulation/);
 assert.match(sql,/CHECK\(NOT external_delivery\)/);
 assert.match(sql,/CHECK\(NOT operational_release\)/);
 assert.match(sql,/UNVERIFIED_SIMULATION_ONLY/);
 assert.match(sql,/employment_status IN \('active','draft'\)/);
 assert.doesNotMatch(sql,/send_email|net\.http_post|https?:\/\//i);
});

test('UI displays autonomous schedule as default and requires no manual draft creation',()=>{
 assert.match(ui,/Autonomer Airline-Dienstplan/);
 assert.match(ui,/autoSlotsResult/);
 assert.match(ui,/autoRunsResult/);
 assert.match(ui,/autoMessagesResult/);
 assert.match(ui,/Alle 24 Stunden/);
 assert.doesNotMatch(ui,/<form action=\{saveSimCrewRosterDraft\}/);
 assert.match(ui,/Autonomes SIM-Szenario/);
});
