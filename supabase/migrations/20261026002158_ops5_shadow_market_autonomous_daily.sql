-- AERVELYS OPS 5.0: autonomous simulated charter-demand intake (shadow mode)
-- Does not release flights, pay invoices, move aircraft, dispatch crew or call external services.
create extension if not exists pg_cron with schema pg_catalog;

alter table public.charter_requests
  add column if not exists origin text not null default 'manual'
  check (origin in ('manual','simulation'));

-- Prevent browser insert from impersonating the unattended simulator.
drop policy if exists charter_requests_owner_create on public.charter_requests;
create policy charter_requests_owner_create on public.charter_requests
 for insert to authenticated
 with check (status='draft' and origin='manual' and
 exists(select 1 from public.organizations o
  where o.id=organization_id and o.owner_user_id=(select auth.uid())));

create table public.simulation_market_ticks (
 id uuid primary key default gen_random_uuid(),
 organization_id uuid not null references public.organizations(id),
 simulation_day date not null,
 status text not null default 'started'
  check(status in ('started','completed')),
 request_id uuid,
 source text not null default 'deterministic_market_v1',
 generated_at timestamptz not null default now(),
 fleet_total integer not null default 0,
 fleet_available integer not null default 0,
 verified_pic integer not null default 0,
 verified_sic integer not null default 0,
 assessment text,
 unique(organization_id,simulation_day),
 foreign key (request_id,organization_id)
  references public.charter_requests(id,organization_id)
);
create index simulation_market_ticks_recent_idx on public.simulation_market_ticks(organization_id, simulation_day desc);
alter table public.simulation_market_ticks enable row level security;
revoke all on public.simulation_market_ticks from anon,authenticated;
grant select on public.simulation_market_ticks to authenticated;
create policy simulation_ticks_owner_read on public.simulation_market_ticks
 for select to authenticated
 using (exists(select 1 from public.organizations o
 where o.id=organization_id and o.owner_user_id=(select auth.uid())));

create or replace function ops_internal.audit_creation()
 returns trigger language plpgsql security definer set search_path=pg_catalog as $$
begin
 insert into public.audit_events
  (organization_id,actor_user_id,actor_role,event_type,resource_type,resource_id,details)
 values (new.organization_id,auth.uid(),
   case when auth.uid() is null then 'simulation_worker' else 'authenticated' end,
   'record_created',TG_TABLE_NAME,new.id,'{}'::jsonb);
 return new;
end; $$;
revoke all on function ops_internal.audit_creation() from public,anon,authenticated;

-- PostgreSQL clock-driven engine. Cron uses DB privileges, not a browser credential.
-- A unique (org, date) constraint makes all execution/retries idempotent.
create or replace function ops_internal.simulate_market_day(p_day date default (now() at time zone 'UTC')::date)
returns integer language plpgsql security invoker set search_path=pg_catalog as $$
declare
 org record;
 v_tick uuid;
 v_request uuid;
 v_origin text;
 v_dest text;
 v_ordinal int;
 v_departure timestamptz;
 v_passengers int;
 v_total int;
 v_available int;
 v_pic int;
 v_sic int;
 v_assessment text;
 v_count int := 0;
begin
 if p_day is null then raise exception 'simulation day required'; end if;
 for org in select id from public.organizations order by id loop
  v_tick := null;
  insert into public.simulation_market_ticks(organization_id,simulation_day)
   values(org.id,p_day)
   on conflict (organization_id,simulation_day) do nothing
   returning id into v_tick;
  if v_tick is null then continue; end if;

  v_ordinal := ((extract(doy from p_day)::int-1) % 5);
  case v_ordinal
   when 0 then v_origin:='EDDB';v_dest:='LFMN';
   when 1 then v_origin:='EDAZ';v_dest:='LSZH';
   when 2 then v_origin:='EDDB';v_dest:='EGLL';
   when 3 then v_origin:='EDAZ';v_dest:='LIML';
   else v_origin:='EDAZ';v_dest:='LOWW';
  end case;
  v_passengers := 2 + (extract(doy from p_day)::int % 4);
  v_departure := ((p_day+2)::timestamp at time zone 'UTC') + interval '12 hours';

  -- Market event is SYNTHETIC. Never sends to a customer or books an aircraft.
  insert into public.charter_requests
   (organization_id,departure_icao,arrival_icao,departure_at,passengers,notes,status,origin)
  values(org.id,v_origin,v_dest,v_departure,v_passengers,
    '[SYNTHETIC - NOT A REAL CUSTOMER] Automatically generated by OPS 5.0 market simulator',
    'draft','simulation')
  returning id into v_request;

  select count(*),count(*) filter(where operational_status='available')
   into v_total,v_available from public.aircraft where organization_id=org.id;
  select count(*) filter(where q.qualification='PIC'),count(*) filter(where q.qualification='SIC')
   into v_pic,v_sic
   from public.crew_qualifications q
   join public.employees e on e.id=q.employee_id and e.organization_id=q.organization_id
   where q.organization_id=org.id and q.status='verified'
      and e.employment_status='active'
      and (q.valid_until is null or q.valid_until >= p_day);
  -- Additional licence/medical/duty/rotation and independent check gates are not
  -- implemented. Regardless of counts, NEVER authorize a simulated flight.
  v_assessment := case
   when v_available=0 then 'BLOCKED: No aircraft is operationally available.'
   when v_pic=0 or v_sic=0 then 'BLOCKED: No independently verified PIC/SIC complement.'
   else 'BLOCKED: Medicals, operator checks, duty time, location and conflicts require verification.'
  end;
  update public.simulation_market_ticks
    set status='completed',request_id=v_request,fleet_total=v_total,
        fleet_available=v_available,verified_pic=v_pic,verified_sic=v_sic,
        assessment=v_assessment
    where id=v_tick;
  insert into public.audit_events(organization_id,actor_role,event_type,resource_type,resource_id,details)
   values(org.id,'simulation_worker','simulated_market_tick','simulation_market_ticks',v_tick,
    jsonb_build_object('generator','deterministic_market_v1','assessment',v_assessment));
  v_count:=v_count+1;
 end loop;
 return v_count;
end; $$;
revoke all on function ops_internal.simulate_market_day(date) from public,anon,authenticated;
comment on function ops_internal.simulate_market_day(date) is
 'Restricted backend-only synthetic daily lead generation; no flight/crew/finance action.';

-- Database-native scheduled automation, independent of Vercel Hobby's daily timing limit.
select cron.schedule('aervelys-ops5-shadow-market-daily','15 5 * * *',
 'select ops_internal.simulate_market_day((now() at time zone ''UTC'')::date);');
